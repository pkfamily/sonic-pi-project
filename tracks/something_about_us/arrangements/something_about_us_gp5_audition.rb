define :play_bar do |events, synth_name, amp, cutoff_value|
  use_synth synth_name; cursor = 0.0
  events.each do |onset, duration, notes, velocity|
    sleep onset - cursor if onset > cursor
    level = amp * velocity / 127.0
    if notes.length > 1
      play_chord notes, attack: 0.01, sustain: 0, release: [duration * 0.82, 0.05].max, cutoff: cutoff_value, amp: level
    else
      play notes[0], attack: 0.01, sustain: 0, release: [duration * 0.82, 0.05].max, cutoff: cutoff_value, amp: level
    end
    cursor = onset
  end
  sleep 4.0 - cursor if cursor < 4.0
end

